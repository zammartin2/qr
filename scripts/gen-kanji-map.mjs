#!/usr/bin/env node
/**
 * Generates src/core/encode/kanji-table.ts — the Unicode -> Shift JIS mapping
 * used by kanji mode (zero runtime dependencies).
 *
 * Method: enumerate every double-byte SJIS pair inside the two ranges covered
 * by ISO/IEC 18004 kanji mode (0x8140–0x9FFC and 0xE040–0xEBBF), decode each
 * pair with Node's built-in TextDecoder('shift_jis'), and keep the first
 * (lowest) SJIS code for each Unicode code point.
 *
 * Requires a full-ICU Node build — official binaries have it; some minimal
 * distributions do not expose 'shift_jis' in TextDecoder.
 *
 * Usage:
 *   node scripts/gen-kanji-map.mjs            # write the table
 *   node scripts/gen-kanji-map.mjs --check    # verify committed file matches
 *
 * Exit codes:
 *   0  success (or --check passed)
 *   1  generation or verification failed
 *   2  environment does not support Shift JIS
 */
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { performance } from 'node:perf_hooks';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const out = join(root, 'src', 'core', 'encode', 'kanji-table.ts');

const checkOnly = process.argv.includes('--check');

// --- environment guard -----------------------------------------------------

let decoder;
try {
  decoder = new TextDecoder('shift_jis');
} catch {
  console.error('error: this Node build does not support TextDecoder("shift_jis").');
  console.error('       Install a full-ICU Node build (official binaries have it).');
  console.error(`       Current Node: ${process.version}, ICU: ${process.versions.icu ?? 'none'}`);
  process.exit(2);
}

// --- table construction ----------------------------------------------------

const entries = []; // [codePoint, sjis]
const seen = new Set();

/** SJIS trail bytes: 0x40–0x7E and 0x80–0xFC, in ascending order. */
const TRAILS = (() => {
  const t = [];
  for (let b = 0x40; b <= 0x7e; b++) t.push(b);
  for (let b = 0x80; b <= 0xfc; b++) t.push(b);
  return t;
})();

/**
 * Decodes one SJIS pair and records it if it maps to a single BMP code point.
 * Pairs are enumerated in ascending SJIS order, so the first hit for a code
 * point is also the lowest SJIS code (deterministic tie-break).
 */
function tryPair(lead, trail) {
  const sjis = (lead << 8) | trail;
  let text;
  try {
    text = decoder.decode(Uint8Array.from([lead, trail]));
  } catch {
    return;
  }
  if (text.length !== 1) return;
  const cp = text.codePointAt(0);
  if (cp === undefined || cp === 0xfffd) return;
  if (seen.has(cp)) return;
  seen.add(cp);
  entries.push([cp, sjis]);
}

// Range 1: 0x8140 - 0x9FFC (ISO/IEC 18004, kanji mode).
for (let lead = 0x81; lead <= 0x9f; lead++) {
  for (const trail of TRAILS) {
    if (((lead << 8) | trail) > 0x9ffc) continue;
    tryPair(lead, trail);
  }
}

// Range 2: 0xE040 - 0xEBBF (ISO/IEC 18004, kanji mode).
for (let lead = 0xe0; lead <= 0xeb; lead++) {
  for (const trail of TRAILS) {
    if (((lead << 8) | trail) > 0xebbf) continue;
    tryPair(lead, trail);
  }
}

// Strictly ascending by Unicode code point — required for binary search.
entries.sort((a, b) => a[0] - b[0]);
for (let i = 1; i < entries.length; i++) {
  if (entries[i][0] <= entries[i - 1][0]) {
    throw new Error(
      `internal error: table not strictly sorted at index ${i} ` +
        `(U+${entries[i][0].toString(16)} <= U+${entries[i - 1][0].toString(16)})`,
    );
  }
}

const flat = new Uint16Array(entries.length * 2);
for (let i = 0; i < entries.length; i++) {
  flat[i * 2] = entries[i][0];
  flat[i * 2 + 1] = entries[i][1];
}

// --- source generation -----------------------------------------------------

const now = new Date().toISOString().slice(0, 10);
const lines = [];
lines.push('/**');
lines.push(' * Unicode -> Shift JIS table for kanji mode.');
lines.push(' *');
lines.push(' * AUTO-GENERATED by scripts/gen-kanji-map.mjs — do not edit by hand.');
lines.push(` * Generated: ${now} with Node ${process.version}.`);
lines.push(' *');
lines.push(' * Strictly ascending pairs of [codePoint, sjis], interleaved in one');
lines.push(' * Uint16 stream. Pure data — no Buffer, no base64, works in every');
lines.push(' * runtime. Binary search requires strict ordering.');
lines.push(' *');
lines.push(` * Entries: ${entries.length}.`);
lines.push(' *');
lines.push(' * @packageDocumentation');
lines.push(' */');
lines.push('');
lines.push('/**');
lines.push(' * Number of table entries. `KANJI_TABLE.length === KANJI_TABLE_SIZE * 2`.');
lines.push(' */');
lines.push(`export const KANJI_TABLE_SIZE: number = ${entries.length};`);
lines.push('');
lines.push('/**');
lines.push(' * Interleaved [codePoint, sjis] pairs, strictly ascending by code point.');
lines.push(' */');
lines.push('export const KANJI_TABLE: Uint16Array = new Uint16Array([');
for (let i = 0; i < flat.length; i += 16) {
  const slice = Array.from(flat.subarray(i, Math.min(i + 16, flat.length)))
    .map((v) => `0x${v.toString(16)}`)
    .join(', ');
  lines.push(`  ${slice},`);
}
lines.push(']);');
lines.push('');

const generated = lines.join('\n');

// --- write or verify -------------------------------------------------------

const relOut = relative(root, out);

if (checkOnly) {
  if (!existsSync(out)) {
    console.error(`error: ${relOut} does not exist — run without --check first.`);
    process.exit(1);
  }
  const current = readFileSync(out, 'utf8');
  // Ignore the "Generated:" date line when comparing — it changes every run.
  const stripDate = (s) => s.replace(/^ \* Generated: .*$/m, ' * Generated: (ignored)');
  if (stripDate(current) !== stripDate(generated)) {
    console.error(`error: ${relOut} is out of date.`);
    console.error('       Re-run `npm run gen:kanji-map` and commit the result.');
    process.exit(1);
  }
  console.log(`ok: ${relOut} matches the generator output (${entries.length} entries).`);
  process.exit(0);
}

const t0 = performance.now();
writeFileSync(out, generated, 'utf8');
const ms = (performance.now() - t0).toFixed(1);

const bytes = Buffer.byteLength(generated);
console.log(
  `written: ${relOut} (${entries.length} entries, ${lines.length} lines, ` +
    `${(bytes / 1024).toFixed(1)} KB, ${ms} ms)`,
);